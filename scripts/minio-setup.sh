#!/usr/bin/env bash
#
# สร้าง MinIO bucket ทั้งหมดที่โปรเจคนี้ใช้ (app + observability stack) พร้อม user/policy
# แยกต่อ bucket (least privilege) แทนการใช้ root credential ตัวเดียวใช้ร่วมกันทุก service
#
#   ./scripts/minio-setup.sh
#   MINIO_ENDPOINT= ./scripts/minio-setup.sh   # ชี้ไป instance อื่น
#
# ไม่มี default ของ MINIO_ROOT_USER/MINIO_ROOT_PASSWORD โดยเจตนา — ต้องกรอกเอง (ผ่าน prompt
# หรือตั้ง env var ไว้ล่วงหน้าเพื่อรันแบบ non-interactive) กัน credential จริงหลุดเข้า shell
# history/CI log โดยไม่ตั้งใจ
#
# idempotent: รันซ้ำได้ ไม่ทับ secret ของ user ที่มีอยู่แล้ว, ไม่ error ถ้า bucket/policy มีอยู่แล้ว
#
# ผลลัพธ์ (access key/secret key ที่ generate ใหม่) พิมพ์ออก stdout และเขียนสำรองไว้ที่ OUT_FILE
# (default scripts/minio-setup.out.env) — เป็นไฟล์ secret ห้าม commit เข้า git

set -euo pipefail

MINIO_ENDPOINT="${MINIO_ENDPOINT:-http://192.168.0.126:9002}"
OUT_FILE="${OUT_FILE:-scripts/minio-setup.out.env}"
ALIAS="minio-setup-local"

# รายชื่อ bucket ของโปรเจค (ตรงกับ default ใน src/config/configuration.ts และ
# observability/docker-compose.yml) — override/เพิ่มได้ผ่าน env var BUCKETS (คั่นด้วยช่องว่าง)
BUCKETS="${BUCKETS:-smtrack-log-archive smtrack-device-images smtrack-firmware tempo-traces loki-chunks}"

POLICY_DIR="$(mktemp -d)"
trap 'rm -rf "$POLICY_DIR"' EXIT

declare -a RESULT_LINES=()

# ── helpers ──────────────────────────────────────────────────────────────────

log()  { printf '\033[1m%s\033[0m\n' "$1"; }
ok()   { printf '  \033[32m✓\033[0m %s\n' "$1"; }
warn() { printf '  \033[33m!\033[0m %s\n' "$1"; }
die()  { printf '\033[31m✗ %s\033[0m\n' "$1" >&2; exit 1; }

# ── 0. รับ root credential ───────────────────────────────────────────────────

log "0. MinIO root credential ($MINIO_ENDPOINT)"

if [[ -z "${MINIO_ROOT_USER:-}" ]]; then
  read -r -p "MinIO root user: " MINIO_ROOT_USER
fi
if [[ -z "${MINIO_ROOT_PASSWORD:-}" ]]; then
  read -r -s -p "MinIO root password: " MINIO_ROOT_PASSWORD
  echo
fi
[[ -n "$MINIO_ROOT_USER" && -n "$MINIO_ROOT_PASSWORD" ]] || die "ต้องกรอก root user และ password"

command -v mc >/dev/null 2>&1 || die "ไม่พบคำสั่ง mc — ติดตั้งก่อน (brew install minio/stable/mc หรือ apt/scoop ตามระบบ)"

mc alias set "$ALIAS" "$MINIO_ENDPOINT" "$MINIO_ROOT_USER" "$MINIO_ROOT_PASSWORD" >/dev/null \
  || die "เชื่อมต่อ/login MinIO ที่ $MINIO_ENDPOINT ไม่สำเร็จ ตรวจ endpoint และ root credential"
ok "login สำเร็จ"

# ── 1. สร้าง bucket + policy + user ต่อ bucket ───────────────────────────────

for BUCKET in $BUCKETS; do
  log "1. bucket: $BUCKET"

  mc mb --ignore-existing "$ALIAS/$BUCKET" >/dev/null
  ok "bucket พร้อมใช้งาน"

  POLICY_NAME="${BUCKET}-rw"
  POLICY_FILE="$POLICY_DIR/${BUCKET}.json"
  cat >"$POLICY_FILE" <<EOF
{
  "Version": "2012-10-17",
  "Statement": [
    {
      "Effect": "Allow",
      "Action": ["s3:ListBucket"],
      "Resource": ["arn:aws:s3:::${BUCKET}"]
    },
    {
      "Effect": "Allow",
      "Action": ["s3:GetObject", "s3:PutObject", "s3:DeleteObject"],
      "Resource": ["arn:aws:s3:::${BUCKET}/*"]
    }
  ]
}
EOF
  mc admin policy create "$ALIAS" "$POLICY_NAME" "$POLICY_FILE" >/dev/null
  ok "policy '$POLICY_NAME' scope เฉพาะ bucket นี้"

  # ชื่อ user = ชื่อ bucket (ตาม pattern ARCHIVE_S3_ACCESS_KEY= ใน .env.example)
  ACCESS_KEY="$BUCKET"
  if mc admin user info "$ALIAS" "$ACCESS_KEY" >/dev/null 2>&1; then
    warn "user '$ACCESS_KEY' มีอยู่แล้ว — ข้ามการสร้าง (secret เดิมยังใช้ได้ ไม่ reset)"
    SECRET_KEY="(ใช้ค่าเดิมที่เคย generate ไว้ — ไม่ได้เก็บ secret ซ้ำในสคริปต์นี้)"
  else
    SECRET_KEY="$(openssl rand -base64 24)"
    mc admin user add "$ALIAS" "$ACCESS_KEY" "$SECRET_KEY" >/dev/null
    ok "สร้าง user '$ACCESS_KEY' แล้ว"
  fi

  mc admin policy attach "$ALIAS" "$POLICY_NAME" --user "$ACCESS_KEY" >/dev/null 2>&1 || true
  ok "attach policy ให้ user แล้ว"

  # sanity check เฉพาะกรณีเพิ่งสร้าง secret ใหม่ (ถ้า skip ไว้ด้านบนไม่มี secret จริงให้ทดสอบ)
  if [[ "$SECRET_KEY" != "(ใช้ค่าเดิมที่เคย generate ไว้ — ไม่ได้เก็บ secret ซ้ำในสคริปต์นี้)" ]]; then
    CHECK_ALIAS="minio-setup-check-${BUCKET}"
    if mc alias set "$CHECK_ALIAS" "$MINIO_ENDPOINT" "$ACCESS_KEY" "$SECRET_KEY" >/dev/null 2>&1 \
      && mc ls "$CHECK_ALIAS/$BUCKET" >/dev/null 2>&1; then
      ok "ทดสอบ login ด้วย user ใหม่ + list bucket สำเร็จ"
    else
      die "user '$ACCESS_KEY' login/list bucket '$BUCKET' ไม่สำเร็จ — ตรวจ policy attach"
    fi
    mc alias remove "$CHECK_ALIAS" >/dev/null 2>&1 || true
  fi

  RESULT_LINES+=("${BUCKET}|${ACCESS_KEY}|${SECRET_KEY}")
done

mc alias remove "$ALIAS" >/dev/null 2>&1 || true

# ── 2. สรุปผล ─────────────────────────────────────────────────────────────────

log "2. สรุป credential ต่อ bucket (secret — ห้าม commit เข้า git)"
printf '%-24s | %-24s | %s\n' "bucket" "access key" "secret key"
{
  echo "# generated by scripts/minio-setup.sh — secret ห้าม commit เข้า git"
  echo "# copy ค่าที่ต้องการไปใส่ .env จริง (ARCHIVE_S3_*/DEVICE_S3_*/FIRMWARE_S3_*/TEMPO_S3_*/LOKI_S3_*)"
} >"$OUT_FILE"

for LINE in "${RESULT_LINES[@]}"; do
  IFS='|' read -r BUCKET ACCESS_KEY SECRET_KEY <<<"$LINE"
  printf '%-24s | %-24s | %s\n' "$BUCKET" "$ACCESS_KEY" "$SECRET_KEY"
  {
    echo ""
    echo "# ${BUCKET}"
    echo "# ${BUCKET}_S3_ACCESS_KEY=${ACCESS_KEY}"
    echo "# ${BUCKET}_S3_SECRET_KEY=${SECRET_KEY}"
  } >>"$OUT_FILE"
done

echo
ok "บันทึกสำรองไว้ที่ $OUT_FILE แล้ว (อย่า commit ไฟล์นี้)"
